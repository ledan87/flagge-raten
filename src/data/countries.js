export function normalizeText(text) {
  return text
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
}

export function matchCountry(input) {
  const normalized = normalizeText(input)
  if (!normalized) return null

  return (
    countries.find((c) => {
      if (normalizeText(c.name) === normalized) return true
      return c.aliases.some((a) => normalizeText(a) === normalized)
    }) ?? null
  )
}

export function searchCountries(query, limit = 8) {
  const normalized = normalizeText(query)
  if (!normalized) return []

  return countries
    .filter((c) => {
      if (normalizeText(c.name).includes(normalized)) return true
      return c.aliases.some((a) => normalizeText(a).includes(normalized))
    })
    .slice(0, limit)
}

export function getCountryByCode(code) {
  return countries.find((c) => c.code === code) ?? null
}

export function flagUrl(code, width = 640) {
  return `https://flagcdn.com/w${width}/${code}.png`
}
